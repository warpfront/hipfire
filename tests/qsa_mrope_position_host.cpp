// Compiles the same scalar implementation concatenated into QSA_MROPE_SRC.
#include "qsa_mrope_position.h"
#include <cstdio>
#include <initializer_list>

static int failures = 0;

static void expect(const char* name, int actual, int expected) {
    if (actual != expected) {
        std::fprintf(stderr, "%s: got %d, expected %d\n", name, actual, expected);
        ++failures;
    }
}

int main() {
    // A 2x3 image occupies original token rows 2..7, then text resumes.
    // These are fixed upstream coordinates, not generated by the helper.
    const int positions[] = {
        0,0,0, 1,1,1, 2,2,2, 2,2,3, 2,2,4, 2,3,2,
        2,3,3, 2,3,4, 5,5,5, 6,6,6, 7,7,7
    };
    const int rows = 11, delta = -3, compress = 4;
    auto pooled = [&](int first, int local, int frequency) {
        return qsa_pooled_key_position(first, local, compress, frequency,
            positions, rows, delta, 11, 10);
    };

    expect("image block first token t", pooled(0, 1, 0), 2);
    expect("image block first token h", pooled(0, 1, 1), 2);
    expect("image block first token w", pooled(0, 1, 2), 4);
    // The last row of block 2 is already post-prompt; selecting it would
    // apply decode delta to token 11 and yield 8 instead of first-row 5.
    for (int frequency : {0, 1, 2}) {
        expect("boundary block first text token", pooled(0, 2, frequency), 5);
        expect("post-prompt decode delta", pooled(0, 3, frequency), 9);
    }
    expect("incremental pool original block t", pooled(1, 0, 0), 2);
    expect("incremental pool original block h", pooled(1, 0, 1), 2);
    expect("incremental pool original block w", pooled(1, 0, 2), 4);
    expect("incremental pool next boundary block", pooled(1, 1, 0), 5);
    // Frequency 34 is outside the h section and must use t.
    expect("h section bound", qsa_mrope_position(7, 34, positions, rows,
        delta, 11, 10), 2);
    expect("null position table keeps scalar token",
        qsa_pooled_key_position(1, 1, 4, 1, nullptr, 0, -3, 11, 10), 8);
    return failures == 0 ? 0 : 1;
}
