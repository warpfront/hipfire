//! Flags migration gate GC: the legacy boolean/value spelling golden.
//!
//! Every distinct env-value grammar the tree reads today is run, by calling the
//! real old reader, over a fixed list of input spellings. The result is the
//! committed golden `tests/golden/flags-legacy-spelling/grammars.tsv`
//! (`grammar<TAB>default<TAB>input<TAB>result`). The typed flag reader of the
//! flags migration (F0b) re-implements the same grammars and must reproduce this
//! file byte for byte for every converted flag while the legacy window is open.
//!
//! `tests/golden/flags-legacy-spelling/names.tsv` (`name<TAB>grammar[,grammar..]`,
//! one row per ledger name, generated by `scripts/flags-golden-names.py`) maps every
//! ledger name to the grammar ids it is read with today.
//!
//! Regenerate the grammar golden (CPU only, no env var):
//!
//! ```text
//! scripts/flags-golden.sh --regen
//! # or: cargo test -p hipfire-runtime --lib -- --ignored regenerate_legacy_spelling_golden
//! ```
//!
//! Encoding. Input `<unset>` is "variable absent", `<empty>` is the empty string,
//! every other input is the literal text. Result: `true`/`false` for a boolean
//! reader (the reader's own answer with the call-site default applied where the
//! reader yields `None`), `none`/`some(<v>)` for an optional value reader,
//! `error` when the reader rejects the spelling, `panic` when it panics. The
//! `default` column is `true`/`false` for boolean grammars and `-` for value
//! grammars.

use super::RuntimeConfig;
use std::panic::{catch_unwind, AssertUnwindSafe};

/// Input spellings, in golden order. `<unset>` and `<empty>` are encoded here as
/// `None` and `Some("")`.
const INPUTS: &[Option<&str>] = &[
    None,
    Some(""),
    Some("0"),
    Some("1"),
    Some("true"),
    Some("false"),
    Some("on"),
    Some("off"),
    Some("2"),
    Some("garbage"),
    Some("TRUE"),
    Some("FALSE"),
    Some("True"),
    Some("ON"),
    Some("OFF"),
    Some("yes"),
    Some("no"),
    Some("YES"),
    Some("1.5"),
    Some("-1"),
];

fn encode_input(input: Option<&str>) -> String {
    match input {
        None => "<unset>".to_owned(),
        Some("") => "<empty>".to_owned(),
        Some(text) => text.to_owned(),
    }
}

/// A `RuntimeConfig` lookup that serves `input` for `name` and nothing else.
fn runtime_config_for(name: &str, input: Option<&str>) -> RuntimeConfig {
    RuntimeConfig::from_lookup(|asked| {
        if asked == name {
            input.map(str::to_owned)
        } else {
            None
        }
    })
}

fn opt_bool(value: Option<bool>, default: bool) -> String {
    value.unwrap_or(default).to_string()
}

fn opt_value<T: std::fmt::Display>(value: Option<T>) -> String {
    match value {
        Some(value) => format!("some({value})"),
        None => "none".to_owned(),
    }
}

type BoolReader = fn(Option<&str>, bool) -> String;
type ValueReader = fn(Option<&str>) -> String;

/// Boolean grammars: id and the real old reader behind it.
const BOOL_GRAMMARS: &[(&str, BoolReader)] = &[
    // `hipfire_config::developer_bool(name, default)`: `1`/`0`, else the default.
    ("developer_bool", |input, default| {
        hipfire_config::parse_developer_bool(input, default).to_string()
    }),
    // `hipfire_config::developer_typed_bool(name)`: `true`/`false`/`1`/`0`
    // (`true`/`false` ASCII case-insensitive), unset is `None`, anything else panics.
    (
        "developer_typed_bool",
        |input, default| match catch_unwind(AssertUnwindSafe(|| {
            hipfire_config::typed_developer_bool_value("legacy-spelling-probe", input)
        })) {
            Ok(value) => opt_bool(value, default),
            Err(_) => "panic".to_owned(),
        },
    ),
    // `FeatureFlags::from_lookup`'s `parse_bool` (`1/true/TRUE/on/ON`,
    // `0/false/FALSE/off/OFF`; anything else, including empty, is unset).
    ("featureflags_parse_bool", |input, default| {
        opt_bool(
            rdna_compute::feature_flags::parse_legacy_flag_bool(input),
            default,
        )
    }),
    // The schema boolean (`ConfigField::parse_cli` on a `ValueRule::Bool` key):
    // `1/true/on/yes` and `0/false/off/no`, ASCII case-insensitive; an unset
    // variable takes the default and every other spelling is rejected.
    ("schema_bool", |input, default| {
        let field = hipfire_config::field("kernel.npu_spillover").expect("schema bool field");
        match input {
            None => default.to_string(),
            Some(raw) => match field.parse_cli(raw) {
                Ok(hipfire_config::ConfigValue::Bool(value)) => value.to_string(),
                Ok(other) => panic!("schema bool parsed to {other:?}"),
                Err(_) => {
                    debug_assert_eq!(hipfire_config::legacy_spelling_schema_bool(raw), None);
                    "error".to_owned()
                }
            },
        }
    }),
    // `value == Some("1")`: `RuntimeConfig::prompt_token_heat`.
    ("eq_one", |input, _default| {
        runtime_config_for("HIPFIRE_PROMPT_TOKEN_HEAT", input)
            .prompt_token_heat
            .to_string()
    }),
    // `value != Some("0")`: `RuntimeConfig::prefill_batched`.
    ("ne_zero", |input, _default| {
        runtime_config_for("HIPFIRE_PREFILL_BATCHED", input)
            .prefill_batched
            .to_string()
    }),
    // `.is_some()` / `.is_ok()` presence test (an empty value counts as present).
    // No named reader: every site is this one-line expression.
    ("presence", |input, _default| input.is_some().to_string()),
    // `RuntimeConfig::normalize_prompt`: `0/false/off/no` are off, everything else on.
    ("runtime_normalize_prompt", |input, _default| {
        runtime_config_for("HIPFIRE_NORMALIZE_PROMPT", input)
            .normalize_prompt
            .to_string()
    }),
    // `RuntimeConfig::dflash_ngram_block`: `1/true/on`, `0/false/off`, else unset.
    ("runtime_tri_on_true", |input, default| {
        opt_bool(
            runtime_config_for("HIPFIRE_DFLASH_NGRAM_BLOCK", input).dflash_ngram_block,
            default,
        )
    }),
    // `RuntimeConfig::tp_use_rccl`: any value but `0`/`false` (ASCII case-insensitive) is on.
    ("runtime_tp_rccl", |input, default| {
        opt_bool(
            runtime_config_for("HIPFIRE_TP_USE_RCCL", input).tp_use_rccl,
            default,
        )
    }),
    // `RuntimeConfig::ngram_draft` through `hipfire_config::parse_tri_state_alias`:
    // only `on/1/true` are on; `auto`, off spellings and garbage are off.
    ("tri_state_alias", |input, _default| {
        runtime_config_for("HIPFIRE_NGRAM_DRAFT", input)
            .ngram_draft
            .to_string()
    }),
];

/// Value grammars: id and the real old reader behind it.
const VALUE_GRAMMARS: &[(&str, ValueReader)] = &[
    // `value.parse::<f64>().ok()`: `RuntimeConfig::yarn_factor`.
    ("float_parse", |input| {
        opt_value(runtime_config_for("HIPFIRE_YARN_FACTOR", input).yarn_factor)
    }),
    // `value.parse::<i64>().ok()`. No named reader: every site is this expression.
    ("int_parse", |input| {
        opt_value(input.and_then(|raw| raw.parse::<i64>().ok()))
    }),
    // The raw string, as `developer_var` / `process_value` serve it (path, shell and
    // string names). No named reader: the value is passed through untouched.
    ("raw_string", |input| opt_value(input)),
    // `value.parse::<usize>().ok()`: `RuntimeConfig::flash_partials_batch`.
    ("uint_parse", |input| {
        opt_value(runtime_config_for("HIPFIRE_FLASH_PARTIALS_BATCH", input).flash_partials_batch)
    }),
];

/// The stable list of grammar ids, sorted.
pub(super) fn grammar_ids() -> Vec<&'static str> {
    let mut ids: Vec<&'static str> = BOOL_GRAMMARS
        .iter()
        .map(|(id, _)| *id)
        .chain(VALUE_GRAMMARS.iter().map(|(id, _)| *id))
        .collect();
    ids.sort_unstable();
    ids
}

const REGEN_HINT: &str = "scripts/flags-golden.sh --regen";

/// The full golden text of `grammars.tsv`.
pub(super) fn render_grammars_tsv() -> String {
    let mut rows: Vec<(&'static str, &'static str, usize, String)> = Vec::new();
    for (id, reader) in BOOL_GRAMMARS {
        for default in ["false", "true"] {
            for (index, input) in INPUTS.iter().enumerate() {
                let result = reader(*input, default == "true");
                rows.push((
                    id,
                    default,
                    index,
                    format!("{}\t{}\t{}\t{}", id, default, encode_input(*input), result),
                ));
            }
        }
    }
    for (id, reader) in VALUE_GRAMMARS {
        for (index, input) in INPUTS.iter().enumerate() {
            let result = reader(*input);
            rows.push((
                id,
                "-",
                index,
                format!("{}\t-\t{}\t{}", id, encode_input(*input), result),
            ));
        }
    }
    rows.sort_by(|a, b| (a.0, a.1, a.2).cmp(&(b.0, b.1, b.2)));
    let mut out = String::new();
    out.push_str("# Flags migration gate GC: legacy-spelling golden. Do not edit by hand.\n");
    out.push_str(&format!("# regenerate: {REGEN_HINT}\n"));
    out.push_str(&format!("# grammar-ids: {}\n", grammar_ids().join(",")));
    out.push_str(&format!(
        "# inputs: {}\n",
        INPUTS
            .iter()
            .map(|input| encode_input(*input))
            .collect::<Vec<_>>()
            .join(",")
    ));
    out.push_str("# columns: grammar<TAB>default<TAB>input<TAB>result\n");
    for (_, _, _, line) in rows {
        out.push_str(&line);
        out.push('\n');
    }
    out
}

fn golden_dir() -> std::path::PathBuf {
    std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../../tests/golden/flags-legacy-spelling")
}

#[test]
fn legacy_spelling_grammars_match_golden() {
    let path = golden_dir().join("grammars.tsv");
    let want = std::fs::read_to_string(&path)
        .unwrap_or_else(|error| panic!("read {}: {error}; run {REGEN_HINT}", path.display()));
    let got = render_grammars_tsv();
    assert!(
        want == got,
        "legacy-spelling grammars diverged from {}; if intended run {REGEN_HINT}\n{}",
        path.display(),
        first_diff(&want, &got)
    );
}

#[test]
fn legacy_spelling_names_map_to_known_grammars() {
    let path = golden_dir().join("names.tsv");
    let text = std::fs::read_to_string(&path)
        .unwrap_or_else(|error| panic!("read {}: {error}", path.display()));
    let known = grammar_ids();
    let mut previous: Option<&str> = None;
    let mut rows = 0usize;
    for line in text.lines().filter(|line| !line.starts_with('#')) {
        let (name, grammars) = line
            .split_once('\t')
            .unwrap_or_else(|| panic!("names.tsv row without a tab: {line:?}"));
        assert!(
            previous.is_none_or(|p| p < name),
            "names.tsv must be sorted and unique at {name}"
        );
        previous = Some(name);
        for id in grammars.split(',') {
            assert!(
                id == "unclassified" || known.contains(&id),
                "names.tsv: {name} maps to unknown grammar {id:?}"
            );
        }
        rows += 1;
    }
    assert!(rows > 2000, "names.tsv looks truncated ({rows} rows)");
    let header = text
        .lines()
        .find(|line| line.starts_with("# grammar-ids: "))
        .expect("header");
    assert_eq!(header, format!("# grammar-ids: {}", known.join(",")));
}

#[test]
#[ignore = "regenerates tests/golden/flags-legacy-spelling/grammars.tsv"]
fn regenerate_legacy_spelling_golden() {
    let path = golden_dir().join("grammars.tsv");
    std::fs::create_dir_all(path.parent().unwrap()).unwrap();
    std::fs::write(&path, render_grammars_tsv()).unwrap();
}

fn first_diff(want: &str, got: &str) -> String {
    let (mut w, mut g) = (want.lines(), got.lines());
    let mut line = 1;
    loop {
        match (w.next(), g.next()) {
            (Some(a), Some(b)) if a == b => line += 1,
            (None, None) => return "no line difference (trailing bytes)".to_owned(),
            (a, b) => {
                return format!(
                    "first difference at line {line}:\n  golden: {a:?}\n  actual: {b:?}"
                )
            }
        }
    }
}
