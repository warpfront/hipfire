//! Projects the pinned lossless RDNA XML catalogs (`isa/<target>.xml.jsonl`) into the
//! variant-keyed runtime rows `src/isa.rs` parses (`$OUT_DIR/<target>.runtime.tbl`).
//!
//! The projection is a pure function of the committed catalogs: no ROCm, no network, no
//! environment input. Every XML encoding is kept, including named unavailable graphics rows;
//! bit layouts and conditions are consumed directly from the catalogs by the codec. A catalog
//! shape this projection does not know is a build error, never a guessed row.

use std::fmt::Write as _;
use std::path::Path;

use serde_json::{Map, Value};

const TARGETS: [&str; 3] = ["gfx1100", "gfx1151", "gfx12"];

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    let manifest = std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR");
    let out = std::env::var("OUT_DIR").expect("OUT_DIR");
    for target in TARGETS {
        let catalog = Path::new(&manifest).join(format!("isa/{target}.xml.jsonl"));
        println!("cargo:rerun-if-changed={}", catalog.display());
        let text = std::fs::read_to_string(&catalog)
            .unwrap_or_else(|e| panic!("{}: {e}", catalog.display()));
        let table = runtime_table(target, &text);
        let path = Path::new(&out).join(format!("{target}.runtime.tbl"));
        std::fs::write(&path, table).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
    }
}

fn runtime_table(target: &str, catalog: &str) -> String {
    let mut lines = catalog.lines();
    let header: Value =
        serde_json::from_str(lines.next().expect("empty catalog")).expect("catalog header");
    assert_eq!(text(&header, "target"), target, "catalog header target");
    let mut table = format!(
        "# Generated by crates/peacemaker-ir/build.rs from isa/{target}.xml.jsonl; XML sha256 {}\n",
        text(&header, "sha256")
    );
    for (index, line) in lines.enumerate() {
        let row: Value = serde_json::from_str(line)
            .unwrap_or_else(|e| panic!("isa/{target}.xml.jsonl row {}: {e}", index + 1));
        project(&mut table, &header, &row);
        table.push('\n');
    }
    table
}

fn object(value: &Value) -> &Map<String, Value> {
    value
        .as_object()
        .unwrap_or_else(|| panic!("expected a JSON object, got {value}"))
}

fn array<'a>(value: &'a Value, key: &str) -> &'a [Value] {
    value[key]
        .as_array()
        .unwrap_or_else(|| panic!("`{key}`: expected an array in {value}"))
}

fn text<'a>(value: &'a Value, key: &str) -> &'a str {
    value[key]
        .as_str()
        .unwrap_or_else(|| panic!("`{key}`: expected a string in {value}"))
}

fn flag(operand: &Value, key: &str) -> bool {
    text(operand, key) == "true"
}

/// Encoding name to runtime form, prefixes first (`VOP3P` before `VOP3`).
fn form(encoding: &str) -> &'static str {
    let name = encoding.strip_prefix("ENC_").unwrap_or(encoding);
    const PREFIXES: [(&str, &str); 12] = [
        ("SOP1", "sop1"),
        ("SOP2", "sop2"),
        ("SOPC", "sopc"),
        ("SOPK", "sopk"),
        ("SOPP", "sopp"),
        ("SMEM", "smem"),
        ("VOP3P", "vop3p"),
        ("VOP3", "vop3"),
        ("VOPD", "vopd"),
        ("VOP1", "vop1"),
        ("VOP2", "vop2"),
        ("VOPC", "vopc"),
    ];
    if let Some((_, form)) = PREFIXES.iter().find(|(prefix, _)| name.starts_with(prefix)) {
        return form;
    }
    match name {
        "DS" | "VDS" | "LDSDIR" | "VDSDIR" => "ds",
        "FLAT_GLOBAL" | "VGLOBAL" => "global",
        "FLAT_SCRATCH" | "VSCRATCH" => "scratch",
        "FLAT" | "VFLAT" => "flat",
        "MUBUF" | "MTBUF" | "VBUFFER" => "buffer",
        "MIMG" | "MIMG_NSA1" | "VIMAGE" | "VSAMPLE" => "image",
        "VINTERP" => "vinterp",
        "EXP" | "VEXPORT" => "export",
        _ => panic!("encoding {encoding} has no runtime form"),
    }
}

/// Counter families follow the existing RDNA ISA-table counter convention.
fn counters(gfx12: bool, memory: &[Value], kind: &str) -> String {
    if memory.is_empty() && kind != "ds" {
        return "-".into();
    }
    match kind {
        "ds" => return (if gfx12 { "Ds:1" } else { "Lgkm:1" }).into(),
        "smem" => return (if gfx12 { "Km:1" } else { "Lgkm:1" }).into(),
        _ => {}
    }
    let read = memory.iter().any(|op| flag(op, "Input"));
    let write = memory.iter().any(|op| flag(op, "Output"));
    let (load, store) = if gfx12 {
        ("Load", "Store")
    } else {
        ("Vm", "Vs")
    };
    let mut result = if read && write {
        format!("{load}:1@rtn,{store}:1@nortn")
    } else {
        format!("{}:1", if read { load } else { store })
    };
    if kind == "flat" {
        result.push_str(if gfx12 { ",Ds:1" } else { ",Lgkm:1" });
    }
    result
}

/// `items` joined by `,`, or `-` when there are none.
fn list<'a>(items: impl Iterator<Item = &'a str>) -> String {
    let joined = items.collect::<Vec<_>>().join(",");
    if joined.is_empty() {
        "-".into()
    } else {
        joined
    }
}

/// One tab-separated variant-keyed row (14 columns; see `src/isa.rs`).
fn project(table: &mut String, header: &Value, row: &Value) {
    let encoding = text(row, "encoding");
    let layout = &header["encodings"][encoding];
    let fields = object(&layout["fields"]);
    let memory = array(row, "memory");
    let all_operands = array(row, "operands");
    let operands: Vec<&Value> = all_operands
        .iter()
        .filter(|o| text(o, "IsImplicit") == "false")
        .filter(|o| {
            o.get("FieldName")
                .and_then(Value::as_str)
                .is_some_and(|f| fields.contains_key(f))
        })
        .collect();
    let kind = form(encoding);
    let atomic = matches!(kind, "global" | "buffer" | "flat" | "scratch")
        && memory.iter().any(|op| flag(op, "Input"))
        && memory.iter().any(|op| flag(op, "Output"));
    let mut grammar = Vec::with_capacity(operands.len());
    for o in &operands {
        let rtn = if atomic && flag(o, "Output") {
            "@rtn"
        } else {
            ""
        };
        grammar.push(format!(
            "{}{rtn}:{}",
            text(o, "FieldName"),
            text(o, "OperandSize")
        ));
    }
    let grammar = list(grammar.iter().map(String::as_str));
    let defs = list(
        operands
            .iter()
            .filter(|o| flag(o, "Output"))
            .map(|o| text(o, "FieldName")),
    );
    let uses = list(
        operands
            .iter()
            .filter(|o| flag(o, "Input"))
            .map(|o| text(o, "FieldName")),
    );
    let mut implicit = Vec::new();
    for op in all_operands {
        let special = match text(op, "OperandType") {
            "OPR_SSRC_SPECIAL_SCC" => "scc",
            "OPR_VCC" => "vcc",
            "OPR_EXEC" | "OPR_SDST_EXEC" => "exec",
            "OPR_SDST_M0" => "m0",
            _ => continue,
        };
        if op.get("FieldName").is_none() {
            let r = if flag(op, "Input") { "r" } else { "" };
            let w = if flag(op, "Output") { "w" } else { "" };
            implicit.push(format!("{special}:{r}{w}"));
        }
    }
    let implicit = list(implicit.iter().map(String::as_str));
    let mut rules = Vec::with_capacity(fields.len());
    for (name, ranges) in fields {
        let width: u32 = ranges
            .as_array()
            .expect("field ranges")
            .iter()
            .map(|r| u32::try_from(r[1].as_u64().expect("field width")).expect("field width"))
            .sum();
        assert!(
            width <= 64,
            "field {name} of {encoding} is {width} bits wide"
        );
        let mask = if width == 64 {
            u64::MAX
        } else {
            (1u64 << width) - 1
        };
        rules.push(format!("{name}:honored:{mask:x}"));
    }
    let oracle = &row["oracle"];
    let sample = match oracle.get("decoded") {
        Some(decoded) => decoded
            .as_array()
            .expect("oracle.decoded")
            .first()
            .map_or_else(
                || text(row, "name"),
                |s| s.as_str().expect("oracle.decoded[0]"),
            ),
        None => text(row, "name"),
    };
    let mut words = String::new();
    if let Some(candidate) = oracle.get("candidate") {
        let hex = candidate.as_str().expect("oracle.candidate");
        assert!(
            hex.len().is_multiple_of(8),
            "oracle.candidate {hex} is not whole dwords"
        );
        for chunk in hex.as_bytes().chunks(8) {
            let bytes = std::str::from_utf8(chunk).unwrap();
            let little = u32::from_str_radix(bytes, 16).expect("oracle.candidate hex");
            if !words.is_empty() {
                words.push(' ');
            }
            write!(words, "{:08x}", little.swap_bytes()).unwrap();
        }
    }
    if words.is_empty() {
        words.push('-');
    }
    let opcode = row["opcode"].as_u64().expect("opcode");
    let variant = row["variant"].as_u64().expect("variant");
    let gfx12 = text(header, "target") == "gfx12";
    write!(
        table,
        "{}\t{kind}\t{opcode:x}\t{grammar}\t{defs}\t{uses}\t{implicit}\t{}\t{sample}\t{words}\t{}\t{encoding}\t{}\t{variant}",
        text(row, "name"),
        counters(gfx12, memory, kind),
        rules.join(","),
        text(row, "condition"),
    )
    .unwrap();
}
