# cdna_card_package.sh OUTDIR [SHA]
#
# Packages a COMMITTED peacemaker-isa CDNA card harness (cdna_card_tierc) as a
# source archive for the MI300X (gfx942) box. The box BUILDS FROM SOURCE; no
# binary is shipped. Emits into OUTDIR:
#   pmcdna-<sha>.tar   git archive of <sha> with prefix pmcdna-<sha>/
#   card_run.sh        on-card build + quick + full driver (executable)
#   SHA256SUMS         checksums of the two files above
#
# This script runs on the dev machine and never touches a GPU, cargo, or
# hipcc. It packages exactly what is committed at SHA: uncommitted edits are
# NOT in the archive. The harness files must be committed first.
#
# Environment:
#   PMCDNA_WORKTREE   worktree to archive (default below)

set -euo pipefail

WORKTREE="${PMCDNA_WORKTREE:-/home/kaden/qcal/release-0.4.2/pm-cdna3}"

# Everything card_run.sh needs at build/run time. Missing at SHA => refuse.
REQUIRED_FILES=(
  Cargo.toml
  Cargo.lock
  crates/peacemaker-isa/Cargo.toml
  crates/peacemaker-isa/examples/cdna_card_tierc.rs
  kernels/src/pm_cdna/fp8_act_producer.gfx942.hip
  kernels/src/pm_cdna/fp8_moe_gate_up.gfx942.hip
  kernels/src/pm_cdna/qsa_fp8_kv.gfx942.hip
  crates/peacemaker-isa/tools/cdna_card_package.sh
  crates/peacemaker-isa/tools/CDNA-CARD-RUNBOOK.md
)

die() { printf 'cdna_card_package: error: %s\n' "$*" >&2; exit 1; }

usage() {
  printf 'usage: %s OUTDIR [SHA]\n  SHA defaults to `git -C %s rev-parse HEAD`.\n' \
    "${0##*/}" "$WORKTREE" >&2
  exit 2
}

[[ $# -ge 1 && $# -le 2 ]] || usage
OUTDIR="$1"
SHA_ARG="${2:-}"

command -v git >/dev/null || die "git not found"
command -v sha256sum >/dev/null || die "sha256sum not found"
command -v tar >/dev/null || die "tar not found"
[[ -d "$WORKTREE" ]] || die "worktree not found: $WORKTREE"
git -C "$WORKTREE" rev-parse --git-dir >/dev/null 2>&1 || die "not a git worktree: $WORKTREE"

if [[ -z "$SHA_ARG" ]]; then
  SHA="$(git -C "$WORKTREE" rev-parse HEAD)"
else
  SHA="$(git -C "$WORKTREE" rev-parse --verify --quiet "${SHA_ARG}^{commit}")" \
    || die "not a commit in $WORKTREE: $SHA_ARG"
fi
[[ "$SHA" =~ ^[0-9a-f]{40}$ ]] || die "unexpected resolved SHA: $SHA"

# 1. Every harness file must be committed at SHA.
missing=()
for f in "${REQUIRED_FILES[@]}"; do
  git -C "$WORKTREE" cat-file -e "${SHA}:${f}" 2>/dev/null || missing+=("$f")
done
if ((${#missing[@]})); then
  {
    printf 'cdna_card_package: error: commit %s lacks required harness file(s):\n' "$SHA"
    printf '  %s\n' "${missing[@]}"
    printf 'Commit the harness first (git add the files above, git commit), then rerun\n'
    printf 'with that commit (default SHA is HEAD). Untracked/uncommitted files are never\n'
    printf 'included in the archive.\n'
  } >&2
  exit 1
fi

# 2. Warn (not fail) if the worktree differs from SHA in harness files.
dirty="$(git -C "$WORKTREE" status --porcelain -- "${REQUIRED_FILES[@]}" 2>/dev/null || true)"
if [[ -n "$dirty" ]]; then
  printf 'cdna_card_package: warning: worktree has uncommitted changes to harness files;\n' >&2
  printf '  the archive contains only what is committed at %s:\n%s\n' "$SHA" "$dirty" >&2
fi

mkdir -p "$OUTDIR"
OUTDIR="$(cd "$OUTDIR" && pwd)"
TAR="pmcdna-${SHA}.tar"
TMP="$(mktemp -d "$OUTDIR/.pmcdna-pkg.XXXXXX")"
trap 'rm -rf "$TMP"' EXIT

# 3. Archive.
git -C "$WORKTREE" archive --format=tar --prefix="pmcdna-${SHA}/" "$SHA" > "$TMP/$TAR"

# 4. Verify the produced tar really holds the harness files.
tar -tf "$TMP/$TAR" > "$TMP/listing"
for f in "${REQUIRED_FILES[@]}"; do
  grep -Fxq "pmcdna-${SHA}/${f}" "$TMP/listing" \
    || die "archive $TAR is missing ${f} (git archive export-ignore or attributes?)"
done

# 5. card_run.sh: SHA baked in, body quoted so nothing expands here.
{
  printf '#!/usr/bin/env bash\n'
  printf '# Generated by crates/peacemaker-isa/tools/cdna_card_package.sh. Source commit baked in below.\n'
  printf 'SHA=%q\n' "$SHA"
  cat <<'CARD_RUN_BODY'
#
# Build cdna_card_tierc FROM SOURCE on the gfx942 box, compile the HIP twins,
# then run the quick gate and the full gate, each as its own g942run.sh call
# with its own receipt. Usage: bash card_run.sh   (from the directory holding
# pmcdna-<sha>.tar and SHA256SUMS). Only the GPU executions use g942run.sh.
#
# Writes only under /scratch/g942/pmcdna/<sha>, plus the shared cargo target
# dir and the prescribed rust/cargo homes.

set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
TAR="pmcdna-${SHA}.tar"
WORK="/scratch/g942/pmcdna/${SHA}"
HSACO_DIR="${WORK}/hsaco"
QUICK_RECEIPT="${WORK}/cdna_card_tierc.quick.json"
FULL_RECEIPT="${WORK}/cdna_card_tierc.json"
G942RUN=/scratch/g942/g942run.sh

die() { printf 'card_run: error: %s\n' "$*" >&2; exit 1; }
step() { printf '\n=== card_run: %s ===\n' "$*"; }

[[ -f "$HERE/$TAR" ]] || die "missing $HERE/$TAR"
[[ -f "$HERE/SHA256SUMS" ]] || die "missing $HERE/SHA256SUMS"
[[ -x "$G942RUN" ]] || die "missing or non-executable $G942RUN"

step "verify checksums"
(cd "$HERE" && sha256sum -c SHA256SUMS)

step "extract source to $WORK"
mkdir -p "$WORK"
tar -xf "$HERE/$TAR" -C "$WORK" --strip-components=1

export RUSTUP_HOME=/scratch/g942/rustup
export CARGO_HOME=/scratch/g942/cargo
export PATH=/scratch/g942/cargo/bin:/opt/rocm/bin:$PATH
export CARGO_TARGET_DIR=/scratch/g942/target-pmcdna

step "toolchain versions (-> $WORK/toolchain.txt)"
{
  printf 'sha=%s\n' "$SHA"
  cargo --version
  rustc --version
  env ROCR_VISIBLE_DEVICES=-1 HIP_VISIBLE_DEVICES=-1 /opt/rocm/bin/hipcc --version
  env ROCR_VISIBLE_DEVICES=-1 HIP_VISIBLE_DEVICES=-1 /opt/rocm/lib/llvm/bin/clang --version
} 2>&1 | tee "$WORK/toolchain.txt"

step "cargo build --release -p peacemaker-isa --features lab --example cdna_card_tierc"
# CPU-only build: hide GPUs from this one cargo process (not exported), so GPU
# processes started later by g942run.sh still see the card.
(cd "$WORK" && ROCR_VISIBLE_DEVICES=-1 HIP_VISIBLE_DEVICES=-1 \
  nice -n 10 cargo build --release -p peacemaker-isa --features lab --example cdna_card_tierc -j 8)
BIN="$CARGO_TARGET_DIR/release/examples/cdna_card_tierc"
[[ -x "$BIN" ]] || die "build produced no $BIN"

step "compile HIP twins to $HSACO_DIR (gfx942)"
mkdir -p "$HSACO_DIR"
for k in fp8_act_producer fp8_moe_gate_up qsa_fp8_kv; do
  ROCR_VISIBLE_DEVICES=-1 HIP_VISIBLE_DEVICES=-1 \
    nice -n 10 /opt/rocm/bin/hipcc --genco --offload-arch=gfx942 -O3 \
    "$WORK/kernels/src/pm_cdna/${k}.gfx942.hip" \
    -o "$HSACO_DIR/${k}.hsaco"
done
ls -l "$HSACO_DIR"

step "QUICK gate (receipt: $QUICK_RECEIPT)"
G942_OWNER=PmCdnaLead "$G942RUN" pmcdna-tierc \
  timeout --signal=KILL 600 "$BIN" --quick \
  --hsaco-dir "$HSACO_DIR" --receipt "$QUICK_RECEIPT"

step "FULL gate (receipt: $FULL_RECEIPT)"
G942_OWNER=PmCdnaLead "$G942RUN" pmcdna-tierc \
  timeout --signal=KILL 600 "$BIN" \
  --hsaco-dir "$HSACO_DIR" --receipt "$FULL_RECEIPT"

step "done"
printf 'receipts:\n  %s\n  %s\n' "$QUICK_RECEIPT" "$FULL_RECEIPT"
CARD_RUN_BODY
} > "$TMP/card_run.sh"
chmod 0755 "$TMP/card_run.sh"
bash -n "$TMP/card_run.sh" || die "generated card_run.sh failed syntax check"

# 6. Publish and checksum.
mv -f "$TMP/$TAR" "$OUTDIR/$TAR"
mv -f "$TMP/card_run.sh" "$OUTDIR/card_run.sh"
(cd "$OUTDIR" && sha256sum "$TAR" card_run.sh > SHA256SUMS)

printf 'packaged commit %s into %s\n' "$SHA" "$OUTDIR"
printf '  %s\n  card_run.sh\n  SHA256SUMS\n' "$TAR"
printf 'on card: bash card_run.sh   (in the transfer directory)\n'
