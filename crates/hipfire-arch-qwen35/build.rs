//! Shared-weight loader ABI identity (`LoaderAbiSha256`, design §3).
//!
//! Hashes the full source of every file that decides how a dense Qwen3.5
//! weight set is produced or interpreted (loader, typed weights, quant
//! representation constants, wire schema), plus the CPU toolchain/codegen
//! identity and this crate's enabled features. Forward/JIT kernel sources are
//! deliberately excluded: two builds that differ only in compute kernels keep
//! one ABI and may share one host generation.

use sha2::{Digest, Sha256};
use std::fmt::Write as _;
use std::path::Path;

/// Workspace-relative loader closure, hashed in full. Any change to a
/// consumer's interpretation of packed weights lands in one of these files.
const LOADER_CLOSURE: &[&str] = &[
    "crates/hipfire-runtime/src/hfq.rs",
    "crates/hipfire-runtime/src/model_load.rs",
    "crates/hipfire-runtime/src/weight_backend.rs",
    "crates/hipfire-runtime/src/llama.rs",
    "crates/hipfire-runtime/src/weight_host.rs",
    "crates/hipfire-arch-qwen35/src/qwen35/config.rs",
    "crates/hipfire-arch-qwen35/src/qwen35/load.rs",
    "crates/hipfire-arch-qwen35/src/qwen35/weights.rs",
    "crates/hipfire-arch-qwen35/src/shared_weights.rs",
];

/// Quant representation constants live in the kernel dispatcher, which
/// experiments edit freely. Hash only the `DType` enum and the top-level
/// `const` items (group byte sizes, codebooks, pads), so a launcher-only
/// change keeps the ABI.
const DISPATCH: &str = "crates/rdna-compute/src/dispatch.rs";

fn dispatch_representation(source: &str) -> String {
    let mut out = String::new();
    let mut in_dtype = false;
    for line in source.lines() {
        if line.starts_with("pub enum DType") {
            in_dtype = true;
        }
        let top_level_const = ["pub const ", "pub(crate) const ", "const "]
            .iter()
            .any(|prefix| line.starts_with(prefix));
        if in_dtype || top_level_const {
            out.push_str(line);
            out.push('\n');
        }
        if in_dtype && line == "}" {
            in_dtype = false;
        }
    }
    assert!(
        out.contains("pub enum DType"),
        "loader ABI: DType enum not found in {DISPATCH}"
    );
    out
}

fn main() {
    let manifest = std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR");
    let root = Path::new(&manifest).join("../..");
    let mut components: Vec<(String, [u8; 32])> = Vec::new();
    for rel in LOADER_CLOSURE {
        let path = root.join(rel);
        println!("cargo:rerun-if-changed={}", path.display());
        let bytes = std::fs::read(&path).unwrap_or_else(|e| panic!("loader ABI: read {rel}: {e}"));
        components.push((rel.to_string(), Sha256::digest(&bytes).into()));
    }
    let dispatch = root.join(DISPATCH);
    println!("cargo:rerun-if-changed={}", dispatch.display());
    let source = std::fs::read_to_string(&dispatch)
        .unwrap_or_else(|e| panic!("loader ABI: read {DISPATCH}: {e}"));
    components.push((
        format!("{DISPATCH}#representation"),
        Sha256::digest(dispatch_representation(&source).as_bytes()).into(),
    ));

    let rustc = std::env::var("RUSTC").unwrap_or_else(|_| "rustc".into());
    let version = std::process::Command::new(&rustc)
        .arg("-vV")
        .output()
        .unwrap_or_else(|e| panic!("loader ABI: {rustc} -vV: {e}"));
    assert!(version.status.success(), "loader ABI: {rustc} -vV failed");
    let mut toolchain = Sha256::new();
    toolchain.update(b"hipfire-loader-abi-toolchain/v1\0");
    toolchain.update(&version.stdout);
    for key in ["TARGET", "OPT_LEVEL", "CARGO_CFG_TARGET_FEATURE"] {
        println!("cargo:rerun-if-env-changed={key}");
        let value = std::env::var(key).unwrap_or_default();
        toolchain.update((key.len() as u64).to_le_bytes());
        toolchain.update(key.as_bytes());
        toolchain.update((value.len() as u64).to_le_bytes());
        toolchain.update(value.as_bytes());
    }
    let mut features = std::env::vars()
        .filter_map(|(k, _)| k.strip_prefix("CARGO_FEATURE_").map(str::to_owned))
        .collect::<Vec<_>>();
    features.sort();
    for feature in &features {
        toolchain.update((feature.len() as u64).to_le_bytes());
        toolchain.update(feature.as_bytes());
    }
    components.push(("toolchain".to_string(), toolchain.finalize().into()));

    let mut out = String::from(
        "/// Generated by build.rs: (component, SHA-256) of the shared-weight loader closure.\n\
         pub const LOADER_ABI_COMPONENTS: &[(&str, [u8; 32])] = &[\n",
    );
    for (name, digest) in &components {
        let _ = writeln!(out, "    ({name:?}, {digest:?}),");
    }
    out.push_str("];\n");
    let dest = Path::new(&std::env::var("OUT_DIR").expect("OUT_DIR")).join("loader_abi.rs");
    std::fs::write(&dest, out)
        .unwrap_or_else(|e| panic!("loader ABI: write {}: {e}", dest.display()));
}
