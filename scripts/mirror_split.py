def die(msg: str) -> "NoReturn":  # noqa: F821
    print(f"mirror-split: error: {msg}", file=sys.stderr)
    sys.exit(1)


def redact(text: str) -> str:
    return re.sub(r"(?<=://)[^/@\s]+@", "", text)


def run(args, cwd=None, env=None, input=None, check=True) -> subprocess.CompletedProcess:
    res = subprocess.run(args, cwd=cwd, env=env, input=input, capture_output=True)
    if check and res.returncode != 0:
        err = redact((res.stderr or b"").decode("utf-8", "replace").strip())
        die(f"`{redact(' '.join(map(str, args[:5])))}...` failed ({res.returncode}): {err}")
    return res


GIT_C = ["-c", "core.hooksPath=/dev/null", "-c", "commit.gpgsign=false", "-c", "core.autocrlf=false"]


def git(repo: Path, *args: str, input: bytes | None = None, env=None, check=True) -> bytes:
    return run(["git", *GIT_C, "-C", str(repo), *args], input=input, env=env, check=check).stdout


class Source:
    def __init__(self, repo: Path, rev: str):
        self.repo = repo
        self.sha = git(repo, "rev-parse", "--verify", f"{rev}^{{commit}}").decode().strip()

    def show(self, path: str) -> bytes | None:
        res = run(["git", "-C", str(self.repo), "cat-file", "blob", f"{self.sha}:{path}"], check=False)
        return res.stdout if res.returncode == 0 else None

    def toml(self, path: str) -> dict | None:
        data = self.show(path)
        return tomllib.loads(data.decode()) if data is not None else None

    def commit_date(self) -> str:
        return git(self.repo, "log", "-1", "--format=%cd", "--date=raw", self.sha).decode().strip()


