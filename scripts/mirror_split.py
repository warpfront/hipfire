"""Sync the PeaceMaker sub-project to its standalone public repository.

    scripts/mirror-split.sh peacemaker [destination]

Never pushes; scripts/mirror-push.sh gates and pushes. The source checkout is only read. The destination
(default mirror-preview/peacemaker under the source checkout) must not exist.
Environment: MIRROR_SOURCE_REV (source commit-ish, default HEAD),
MIRROR_FILTER_REPO (path of git-filter-repo 2.47.0 if it is not on PATH).

peacemaker -- history-preserving filter (branch `main`)
  Fetches the full history of the source commit into a throw-away repository over
  file:// (the equivalent of `git clone --no-local --single-branch`) and rewrites
  it with git-filter-repo:
    * keeps the path-dependency closure of peacemaker-ir/-lift/-author/-npu/-isa/-rip
      (derived from committed manifests), LICENSE-APACHE / LICENSE-MIT / NOTICE
      and the listed fixtures. Historical crate directories are path-renamed to
      their current PeaceMaker names. Source root Cargo.toml / README history
      is NOT kept;
    * kept blobs are byte-for-byte copies of the source blobs;
    * every commit gets the neutral message `Mirror source update` plus the
      canonical source commit hash; author/committer dates and topology are
      preserved; author and committer names/emails are normalized with the
      checked-in scripts/mirror.mailmap (tool configuration, not mirrored; it is
      applied on every run, whatever MIRROR_SOURCE_REV is);
    * one top commit (dated like the source commit, stable identity) adds the
      generated root files: Cargo.toml (inherited workspace.package keys and only
      the workspace dependencies the closure uses), a Cargo.lock pruned from the
      source lock and settled with `cargo metadata`, LICENSE, LICENSE-LLVM-EXCEPTION, README.md and .gitignore.

Text generated by this script (README, root manifest, lockfile) is checked for
private paths and machine names and the run fails if any appear. Copied source
content is not inspected or altered.
"""
