# TOML emission
# ---------------------------------------------------------------------------
def toml_key(key: str) -> str:
    return key if re.fullmatch(r"[A-Za-z0-9_-]+", key) else json.dumps(key)


def toml_val(v) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(v)
    if isinstance(v, str):
        return json.dumps(v)
    if isinstance(v, list):
        return "[" + ", ".join(toml_val(x) for x in v) + "]"
    if isinstance(v, dict):
        return "{ " + ", ".join(f"{toml_key(k)} = {toml_val(x)}" for k, x in v.items()) + " }" if v else "{}"
    raise TypeError(f"unsupported TOML value {v!r}")


def render_root_manifest(names, manifests, root_manifest, title) -> str:
    ws = root_manifest.get("workspace", {})
    pkg, deps = inherited(manifests, names, ws)
    lines = [
        "# SPDX-License-Identifier: Apache-2.0",
        f"# Generated by scripts/mirror-split.sh in the canonical hipfire repository for the {title}",
        "# mirror: the inherited workspace package keys and only the workspace dependencies",
        f"# the crates below actually use. Edit {CANONICAL} instead.",
        "[workspace]", 'resolver = "2"', "members = [", *[f'    "crates/{n}",' for n in names], "]", "",
        "[workspace.package]",
        *[f"{toml_key(k)} = {toml_val(v)}" for k, v in ws["package"].items() if k in pkg],
        "", "[workspace.dependencies]",
        *[f"{toml_key(k)} = {toml_val(v)}" for k, v in ws["dependencies"].items() if k in deps],
    ]
    return "\n".join(lines) + "\n"


def prune_lock(text: str, names: set[str]) -> str | None:
    blocks = re.split(r"\n(?=\[\[package\]\]\n)", text)
    header, pkgs = blocks[0], blocks[1:]
    if not pkgs:
        return None
    parsed = [tomllib.loads(b)["package"][0] for b in pkgs]
    by_name: dict[str, list[int]] = {}
    for i, p in enumerate(parsed):
        by_name.setdefault(p["name"], []).append(i)

    def resolve(dep: str) -> int | None:
        parts = dep.split(" ", 2)
        cands = by_name.get(parts[0], [])
        if len(parts) > 1:
            cands = [i for i in cands if parsed[i]["version"] == parts[1]]
        if len(parts) > 2:
            cands = [i for i in cands if parsed[i].get("source") == parts[2].strip("()")]
        return cands[0] if len(cands) == 1 else None

    keep: set[int] = set()
    stack = [i for i, p in enumerate(parsed) if p["name"] in names and "source" not in p]
    while stack:
        i = stack.pop()
        if i in keep:
            continue
        keep.add(i)
        for dep in parsed[i].get("dependencies", []):
            j = resolve(dep)
            if j is None:
                return None
            stack.append(j)
    return "\n\n".join([header.rstrip("\n")] + [pkgs[i].strip("\n") for i in sorted(keep)]) + "\n"


def settle_lock(work: Path) -> bool:
    """Let cargo reconcile Cargo.lock (never builds). Returns True if cargo ran successfully."""
    if not shutil.which("cargo"):
        return False
    for extra in (["--offline"], []):
        if run(["cargo", "metadata", "--format-version", "1", *extra], cwd=work, check=False).returncode == 0:
            return True
    print("mirror-split: warning: `cargo metadata` failed; Cargo.lock left as generated "
          "(the first cargo command will settle it)", file=sys.stderr)
    return False


