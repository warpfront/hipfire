"""Flash Next image HTTP smoke and cancellation check against an existing serve.

Does not start/stop the daemon, download models, change configuration, or claim
throughput. Prompts live in this script; real images are committed fixtures.
Save the JSON and read every decoded answer, especially the OCR/description.

    python3 scripts/check_qwen4_vision.py --base-url http://127.0.0.1:11435 \
        --model qwen3.8:flash-next --output /tmp/qwen4-vision-http.json

--expect-vision describes loaded image capability, not a vision_mode setting.
Use on when Flash Next auto, resident, or on has loaded a resident tower.
Use off for vision_mode=off or auto/resident without a sidecar: discovery must omit image,
every image request must be refused, and a text request must still succeed.
Start serve with the desired mode before invoking this instrument; it neither
reloads models nor tests required-sidecar load failures or the memory budget.
"""

import argparse
import base64
import hashlib
import json
import os
from pathlib import Path
import re
import struct
import time
import unicodedata
import urllib.error
import urllib.request
import zlib

ROOT = Path(__file__).resolve().parents[1]
COLOR_PROMPT = "What is the dominant color of this image? Reply with one English color word."
OCR_PROMPT = "Read the text on all five direction signs. Transcribe the visible words in their original language."
DESCRIPTION_PROMPT = "Describe the animal and its pose in this image in one short English sentence."
TEXT_PROMPT = "Compute 7 + 5. Reply with the integer only."
CANCEL_PROMPT = "Describe every detail in this image, then write a long numbered list of possible captions."


def digest(data):
    return hashlib.sha256(data).hexdigest()


def png_bytes(rgb, width=32, height=32):
    """Deterministic RGB PNG using only the Python standard library."""
    def chunk(kind, data):
        return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data) & 0xFFFFFFFF)
    scanlines = (b"\x00" + bytes(rgb) * width) * height
    return (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0))
            + chunk(b"IDAT", zlib.compress(scanlines, 9)) + chunk(b"IEND", b""))


def fixtures():
    result = []
    for name, rgb in [("red", (255, 0, 0)), ("green", (0, 255, 0)), ("blue", (0, 0, 255))]:
        result.append((name, png_bytes(rgb), "image/png", COLOR_PROMPT, [name], "generated by committed script"))
    for name, path, prompt, checks in [
        ("ocr_signs", "benchmarks/vision/images/scene_1.jpg", OCR_PROMPT, ["louvre", "royal"]),
        ("description_dog", "benchmarks/vision/images/doge_napping.png", DESCRIPTION_PROMPT, ["dog"]),
    ]:
        result.append((name, (ROOT / path).read_bytes(), "image/png" if path.endswith(".png") else "image/jpeg", prompt, checks, path))
    return result


def request_body(model, image, mime, prompt, stream, max_tokens):
    content = prompt if image is None else [
        {"type": "image_url", "image_url": {"url": "data:" + mime + ";base64," + base64.b64encode(image).decode()}},
        {"type": "text", "text": prompt},
    ]
    return {"model": model, "messages": [{"role": "user", "content": content}],
            "temperature": 0, "top_p": 1, "seed": 0, "reasoning_effort": "none",
            "max_tokens": max_tokens, "stream": stream}


def http_request(args, path, body=None):
    headers = {"Content-Type": "application/json", "Connection": "close"}
    key = os.environ.get(args.api_key_env)
    if key:
        headers["Authorization"] = "Bearer " + key
    req = urllib.request.Request(args.base_url.rstrip("/") + path,
                                 data=None if body is None else json.dumps(body, separators=(",", ":")).encode(),
                                 headers=headers)
    return urllib.request.urlopen(req, timeout=args.timeout)


def chat(args, body, cancel=False):
    started = time.monotonic()
    result = {"stream": body["stream"], "text": "", "finish_reason": None,
              "request_sha256": digest(json.dumps(body, sort_keys=True, separators=(",", ":")).encode())}
    try:
        with http_request(args, "/v1/chat/completions", body) as response:
            result["http_status"] = response.status
            if not body["stream"]:
                value = json.load(response)
                result["response"] = value
                if "error" in value:
                    result["error"] = value["error"]
                else:
                    choice = value["choices"][0]
                    result["text"] = choice["message"].get("content") or ""
                    result["finish_reason"] = choice.get("finish_reason")
            else:
                events = []
                result["events"] = events
                for line in response:
                    if not line.startswith(b"data:"):
                        continue
                    data = line[5:].strip()
                    if data == b"[DONE]":
                        result["done"] = True
                        break
                    value = json.loads(data)
                    events.append(value)
                    if "error" in value:
                        result["error"] = value["error"]
                        break
                    for choice in value.get("choices", []):
                        text = choice.get("delta", {}).get("content") or ""
                        if text and "first_content_ms" not in result:
                            result["first_content_ms"] = 1000 * (time.monotonic() - started)
                        result["text"] += text
                        if choice.get("finish_reason") is not None:
                            result["finish_reason"] = choice["finish_reason"]
                    if cancel and result["text"] and result["finish_reason"] is None:
                        # Closing the response/socket exercises the serve's
                        # ChannelBody drop cancellation, not a pretend client flag.
                        result["client_disconnected_before_terminal"] = True
                        break
                if not result.get("done") and not result.get("client_disconnected_before_terminal") and "error" not in result:
                    result["error"] = "SSE ended without [DONE]"
    except urllib.error.HTTPError as error:
        result["http_status"] = error.code
        result["error"] = error.read().decode(errors="replace")
    except Exception as error:
        result["error"] = f"{type(error).__name__}: {error}"
    result["elapsed_ms"] = 1000 * (time.monotonic() - started)
    return result


def normalized(text):
    text = unicodedata.normalize("NFKD", text.lower())
    return "".join(c for c in text if not unicodedata.combining(c))


def inspect_result(result, expected, expect_refusal=False):
    if expect_refusal:
        # A timeout, 5xx, or broken stream is not a valid modality refusal.
        status = result.get("http_status", 0)
        return "error" in result and 400 <= status < 500 and "vision" in str(result["error"]).lower()
    if "error" in result or not result["text"].strip() or result["finish_reason"] is None:
        return False
    answer = normalized(result["text"])
    return all(re.search(r"\b" + re.escape(word) + r"\b", answer) for word in expected)


def save(args, report):
    args.output.parent.mkdir(parents=True, exist_ok=True)
    temporary = args.output.with_suffix(args.output.suffix + ".tmp")
    temporary.write_text(json.dumps(report, indent=2, ensure_ascii=False) + "\n")
    temporary.replace(args.output)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--base-url", default="http://127.0.0.1:11435", help="serve origin without /v1")
    parser.add_argument("--model", required=True)
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument("--expect-vision", choices=["on", "off"], default="on",
                        help="expected loaded image capability, not a mode setter: on means a loaded tower; off includes auto/resident without a sidecar")
    parser.add_argument("--timeout", type=float, default=120)
    parser.add_argument("--max-tokens", type=int, default=128)
    parser.add_argument("--api-key-env", default="HIPFIRE_API_KEY", help="environment variable name; key is never stored")
    parser.add_argument("--identity-json", type=Path, help="optional existing model/binary SHA receipt to embed")
    parser.add_argument("--dry-run", action="store_true", help="write exact fixture/prompt identities without HTTP requests")
    args = parser.parse_args()
    if args.base_url.endswith("/v1"):
        parser.error("--base-url must be the origin without /v1")
    if args.timeout <= 0 or args.max_tokens <= 0:
        parser.error("timeout and max-tokens must be positive")
    report = {"schema": "hipfire.qwen4.vision.http.v1", "model": args.model,
              "base_url": args.base_url, "expect_vision": args.expect_vision,
              "status": "incomplete", "cases": [], "script_sha256": digest(Path(__file__).read_bytes()),
              "scope": "HTTP image smoke, modality discovery, disconnect/follow-up lifecycle; no performance or reference-parity claim",
              "human_review_required": ["ocr_signs", "description_dog"],
              "identity": json.loads(args.identity_json.read_text()) if args.identity_json else None}
    cases = fixtures()
    report["fixtures"] = [{"name": name, "source": source, "image_sha256": digest(image),
                            "image_bytes": len(image), "prompt": prompt,
                            "prompt_sha256": digest(prompt.encode()), "prompt_md5": hashlib.md5(prompt.encode()).hexdigest(),
                            "required_answer_words": expected} for name, image, mime, prompt, expected, source in cases]
    save(args, report)
    if args.dry_run:
        report["status"] = "not_run"
        save(args, report)
        print(args.output)
        return 0
    try:
        with http_request(args, "/v1/models") as response:
            report["model_discovery"] = json.load(response)
        resident = next((m for m in report["model_discovery"]["data"] if m["id"] == args.model), None)
        modalities = (resident or {}).get("architecture", {}).get("input_modalities")
        report["discovery_pass"] = (modalities is not None and "text" in modalities
                                    and (("image" in modalities) == (args.expect_vision == "on")))
        if not report["discovery_pass"]:
            raise RuntimeError(f"resident model modalities disagree: {modalities}")
        for name, image, mime, prompt, expected, source in cases:
            for stream in [False, True]:
                result = chat(args, request_body(args.model, image, mime, prompt, stream, args.max_tokens))
                result.update(name=name, image_sha256=digest(image), prompt_md5=hashlib.md5(prompt.encode()).hexdigest())
                result["pass"] = inspect_result(result, expected, expect_refusal=args.expect_vision == "off")
                report["cases"].append(result)
                save(args, report)
                print(f"{name} stream={stream}: {'PASS' if result['pass'] else 'FAIL'} {result['text']!r}", flush=True)
        if args.expect_vision == "on":
            _, red, mime, prompt, _, _ = cases[0]
            for stream in [False, True]:
                body = request_body(args.model, red, mime, prompt, stream, 32)
                body["stop"] = ["Red"]
                stopped = chat(args, body)
                stopped.update(name="image_stop_control", image_sha256=digest(red),
                               prompt_md5=hashlib.md5(prompt.encode()).hexdigest())
                stopped["pass"] = ("error" not in stopped and stopped.get("finish_reason") == "stop"
                                   and "red" not in stopped["text"].lower())
                report["cases"].append(stopped)
                save(args, report)
            body = request_body(args.model, red, mime, prompt, False, 128)
            body.update(reasoning_effort="low", max_think_tokens=16)
            thinking = chat(args, body)
            message = thinking.get("response", {}).get("choices", [{}])[0].get("message", {})
            thinking.update(name="image_reasoning_control", image_sha256=digest(red),
                            prompt_md5=hashlib.md5(prompt.encode()).hexdigest())
            thinking["pass"] = (inspect_result(thinking, ["red"])
                                and bool(message.get("reasoning_content")))
            report["cases"].append(thinking)
            save(args, report)
            # The source is only 1 MP, but merge-aligned smart resize would
            # expand this extreme aspect ratio beyond the tower's LDS bound.
            # It must fail before tower execution, then leave later turns usable.
            extreme = png_bytes((255, 0, 0), width=1_048_576, height=1)
            refused = chat(args, request_body(args.model, extreme, "image/png", COLOR_PROMPT, False, 32))
            refused.update(name="extreme_aspect_ratio_refused", image_sha256=digest(extreme),
                           prompt_md5=hashlib.md5(COLOR_PROMPT.encode()).hexdigest())
            refused["pass"] = ("error" in refused and 400 <= refused.get("http_status", 0) < 500)
            report["cases"].append(refused)
            save(args, report)
            _, image, mime, _, _, _ = cases[-1]
            cancelled = chat(args, request_body(args.model, image, mime, CANCEL_PROMPT, True, 512), cancel=True)
            cancelled.update(name="cancel_image_stream", **{"pass": bool(cancelled.get("client_disconnected_before_terminal"))})
            report["cases"].append(cancelled)
            save(args, report)
        text = chat(args, request_body(args.model, None, None, TEXT_PROMPT, False, 32))
        text.update(name="text_after_image_or_cancel", **{"pass": inspect_result(text, ["12"])})
        report["cases"].append(text)
        save(args, report)
        if args.expect_vision == "on":
            name, image, mime, prompt, expected, _ = cases[2]
            follow = chat(args, request_body(args.model, image, mime, prompt, True, 32))
            follow.update(name="blue_after_cancel_and_text", **{"pass": inspect_result(follow, expected)})
            report["cases"].append(follow)
        report["status"] = "pass" if all(case["pass"] for case in report["cases"]) else "fail"
    except Exception as error:
        report["error"] = f"{type(error).__name__}: {error}"
        report["status"] = "fail"
    save(args, report)
    print(f"{report['status']}: {args.output}")
    return 0 if report["status"] == "pass" else 1


if __name__ == "__main__":
    raise SystemExit(main())
