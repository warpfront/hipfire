"""Lifecycle check: deprecated surfaces stay opt-in, and every knob has a status.

(a) No default config path reaches deprecated code:
    - every config field marked `// lifecycle: deprecated since …` is either a
      gate whose schema default is inert (off / empty / false) or a tuning knob
      that only matters once a gate is on;
    - the default KV names (`memory.kv_cache`, `memory.kv_k`) and the Qwen/llama
      `auto` resolution never select a deprecated KV name or Givens asym mode;
    - registry cards and the copyable `docs/configs/*.toml` profiles never set
      a deprecated key or value;
    - CI entry points (`scripts/no-gpu-ci.sh`, `.github/workflows/*`,
      `.githooks/*`) never invoke a deprecated script;
    - deprecated code that IS reached by default (only the extension-based
      MQ4R / DS4 MQ2R route selection) is listed in DEFAULT_REACHED_ALLOWLIST.
(b) Every env var and config key carries a lifecycle status:
    - `docs/CONFIG.md` lifecycle table == schema keys + derived status;
    - `docs/env-vars.md` generated inventory == `HIPFIRE_*` token scan + status.

`--write` regenerates both generated tables. Exit 0 = pass, 1 = drift/violation.
"""

from __future__ import annotations

import json
import re
import subprocess
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MARK = "lifecycle: deprecated since 0.4.0, removal 0.5.0"
CONFIG_RS = ROOT / "crates/hipfire-config/src/lib.rs"
KV_MODE_RS = ROOT / "crates/hipfire-runtime/src/kv_mode.rs"
CONFIG_MD = ROOT / "docs/CONFIG.md"
ENV_MD = ROOT / "docs/env-vars.md"
CFG_BEGIN = "<!-- lifecycle-table:begin (generated by scripts/check-lifecycle.py --write) -->"
CFG_END = "<!-- lifecycle-table:end -->"
ENV_BEGIN = "<!-- env-inventory:begin (generated by scripts/check-lifecycle.py --write) -->"
ENV_END = "<!-- env-inventory:end -->"

