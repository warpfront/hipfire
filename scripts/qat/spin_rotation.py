            for meta in producer_meta.values():
                meta["file"] = str(Path(meta["file"]).relative_to(args.out))
            manifest["capture"]["blocks"][str(block)] = {
                "status": "complete",
                "type": block_type,
                "input_boundary": str(block),
                "output_boundary": str(block + 1),
                "producer_sites": producer_meta,
            }
