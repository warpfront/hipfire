def fold_audit(source_path: Path) -> dict[str, Any]:
    index = json.loads((source_path / "model.safetensors.index.json").read_text())
    names = set(index["weight_map"])
    expected: set[str] = {
        "model.language_model.embed_tokens.weight",
        "model.language_model.norm.weight",
        "lm_head.weight",
    }
    readers: list[str] = []
    writers: list[str] = []
    norms: list[str] = []
    for block in range(64):
        prefix = f"model.language_model.layers.{block}."
        layer_readers = _reader_names(block) + [
            prefix + "mlp.gate_proj.weight",
            prefix + "mlp.up_proj.weight",
        ]
        layer_writers = [
            prefix + ("self_attn.o_proj.weight" if block % 4 == 3 else "linear_attn.out_proj.weight"),
            prefix + "mlp.down_proj.weight",
        ]
        layer_norms = [
            prefix + "input_layernorm.weight",
            prefix + "post_attention_layernorm.weight",
        ]
        readers.extend(layer_readers)
        writers.extend(layer_writers)
        norms.extend(layer_norms)
        expected.update(layer_readers + layer_writers + layer_norms)
    missing = sorted(expected - names)
    text_names = sorted(name for name in names if name.startswith("model.language_model.") or name == "lm_head.weight")
    allowed_untouched_suffixes = (
        ".A_log",
        ".dt_bias",
        ".conv1d.weight",
        ".linear_attn.norm.weight",
        ".self_attn.q_norm.weight",
        ".self_attn.k_norm.weight",
    )
    known = expected | {name for name in text_names if name.endswith(allowed_untouched_suffixes)}
    unknown = sorted(set(text_names) - known)
    if missing or unknown:
        raise RuntimeError(f"fold tensor audit failed: missing={missing}, unknown={unknown}")
    return {
        "readers": readers,
        "writers": writers,
        "norms": norms,
        "reader_count": len(readers),
        "writer_count": len(writers),
        "norm_count": len(norms),
        "bias_tensors": [name for name in text_names if name.endswith(".bias")],
        "unknown_residual_side_tensors": unknown,
        "untouched_text_tensors": sorted(set(text_names) - expected),
    }


def synthetic_fold_identity(source_path: Path, rotation: torch.Tensor, device: torch.device) -> dict[str, float]:
    source = SafeTensorSource(source_path)
    generator = torch.Generator(device=device).manual_seed(20260920)
    x = torch.randn((32, HIDDEN), generator=generator, device=device)
    x = x / x.square().mean(dim=-1, keepdim=True).sqrt()
    block = 0
    norm_name = f"model.language_model.layers.{block}.input_layernorm.weight"
    weight_name = f"model.language_model.layers.{block}.linear_attn.in_proj_b.weight"
    gain = bf16_gain(source.get(norm_name)).to(device)
    weight = source.get(weight_name).float().to(device)
    original = (x * gain) @ weight.T
    rotated_x = x @ rotation
    folded_w = (weight * gain) @ rotation
    folded = rotated_x @ folded_w.T
    error = folded - original
    return {
        "max_abs": float(error.abs().max().item()),
        "rms": float(error.square().mean().sqrt().item()),
        "reference_rms": float(original.square().mean().sqrt().item()),
        "relative_rms": float(error.square().sum().sqrt().div(original.square().sum().sqrt()).item()),
    }


def _load_rotation(path: Path, device: torch.device) -> torch.Tensor:
    value = torch.load(path, map_location="cpu", weights_only=True)
    if isinstance(value, dict):
        value = value.get("R1", value.get("rotation"))
    if not isinstance(value, torch.Tensor) or tuple(value.shape) != (HIDDEN, HIDDEN):
        raise ValueError(f"rotation must be F32[{HIDDEN},{HIDDEN}]")
    rotation = value.float().to(device)
    maximum, _ = orthogonality_error(rotation)
    if maximum > 5e-4:
        raise ValueError(f"rotation is not orthogonal: max |R^T R-I|={maximum}")
    return rotation


