@dataclass
class ProjectionSite:
    block: int
    name: str
    x_base_train: torch.Tensor
    x_base_heldout: torch.Tensor
    x_original_train: torch.Tensor
    x_original_heldout: torch.Tensor
    weight: torch.Tensor
    folded_weight: torch.Tensor
    scale: torch.Tensor
    train_order: torch.Tensor
    heldout_order: torch.Tensor

    def loss(
        self,
        rotation: torch.Tensor,
        batch: int,
        step: int,
        activation_weight: float,
    ) -> dict[str, torch.Tensor]:
        count = self.x_base_train.shape[0]
        offset = (step * batch) % count
        if offset + batch <= count:
            indices = self.train_order[offset : offset + batch]
        else:
            indices = torch.cat((self.train_order[offset:], self.train_order[: batch - (count - offset)]))
        xb = self.x_base_train.index_select(0, indices)
        xo = self.x_original_train.index_select(0, indices)
        metrics = self._metrics(rotation, xb, xo, ste=True)
        metrics["loss"] = (
            activation_weight * metrics["activation4"]
            + metrics["weight4"]
            + metrics["output4"]
            + 0.25 * metrics["output8"]
        )
        return metrics

    def heldout(self, rotation: torch.Tensor, limit: int) -> dict[str, torch.Tensor]:
        indices = self.heldout_order[: min(limit, self.heldout_order.numel())]
        xb = self.x_base_heldout.index_select(0, indices)
        xo = self.x_original_heldout.index_select(0, indices)
        return self._metrics(rotation, xb, xo, ste=False)

    def _metrics(
        self, rotation: torch.Tensor, xb: torch.Tensor, xo: torch.Tensor, ste: bool
    ) -> dict[str, torch.Tensor]:
        x_rotated = xb @ rotation
        w_rotated = self.folded_weight @ rotation
        z = runtime_basis_rows(x_rotated / self.scale)
        u = runtime_basis_rows(w_rotated * self.scale)
        qw = mq4v2_fake(u)
        if ste:
            qa4 = a4_ste(z.T.contiguous(), FUSED4).T
            qa8 = a8_ste(z.T.contiguous(), "f32").T
        else:
            qa4 = a4_forward(z.T.contiguous(), FUSED4)[0].T
            qa8 = a8_forward(z.T.contiguous(), "f32")[0].T
        reference = xo @ self.weight.T
        y4 = qa4 @ qw.T
        y8 = qa8 @ qw.T
        activation4 = relative_mse(qa4, z)
        weight4 = relative_mse(qw, u)
        output4 = relative_mse(y4, reference)
        output8 = relative_mse(y8, reference)
        total = activation4 + weight4 + output4 + 0.25 * output8
        return {
            "loss": total,
            "activation4": activation4,
            "weight4": weight4,
            "output4": output4,
            "output8": output8,
        }


def _sample_weight_rows(
    source: SafeTensorSource, names: list[str], rows: int, seed: int
) -> torch.Tensor:
    rng = np.random.Generator(np.random.PCG64(seed))
    shapes = [(name, int(source.get(name).shape[0])) for name in names]
    total = sum(size for _, size in shapes)
    chosen = np.sort(rng.choice(total, size=min(rows, total), replace=False))
    pieces: list[torch.Tensor] = []
    base = 0
    for name, size in shapes:
        local = chosen[(chosen >= base) & (chosen < base + size)] - base
        if local.size:
            full = source.get(name)
            pieces.append(full.index_select(0, torch.from_numpy(local.astype(np.int64))).float())
        base += size
    return torch.cat(pieces, dim=0)


def load_projection_sites(
    source_path: Path,
    capture_path: Path,
    blocks: list[int],
    weight_rows: int,
    device: torch.device,
    seed: int,
) -> tuple[list[ProjectionSite], dict[str, Any]]:
    manifest = json.loads((capture_path / "manifest.json").read_text())
    source = SafeTensorSource(source_path)
    sites: list[ProjectionSite] = []
    split_sequence = int(manifest["corpus"]["train_sequences"])
    seq_len = int(manifest["corpus"]["sequence_length"])
    for block in blocks:
        block_meta = manifest.get("capture", {}).get("blocks", {}).get(str(block))
        if not block_meta or block_meta.get("status") != "complete":
            raise RuntimeError(f"capture block {block} is not complete")
        for site_index, site_name in enumerate(_site_names(block)):
            meta = block_meta["producer_sites"][site_name]
            shape = tuple(int(v) for v in meta["shape"])
            array = np.memmap(capture_path / meta["file"], dtype="<f4", mode="r", shape=shape)
            global_indices = np.asarray(meta["global_sample_indices"], dtype=np.int64)
            is_train = global_indices < split_sequence * seq_len
            train = torch.from_numpy(np.asarray(array[is_train]).copy()).to(device)
            heldout = torch.from_numpy(np.asarray(array[~is_train]).copy()).to(device)
            gain = bf16_gain(source.get(_norm_name(block, site_name))).to(device)
            x_base_train = train / gain
            x_base_heldout = heldout / gain
            names = _site_weight_names(block, site_name)
            weight = _sample_weight_rows(
                source, names, weight_rows, seed + block * 101 + site_index
            ).to(device)
            folded_weight = weight * gain
            scale = compute_awq_scales(train.square().sum(dim=0), ALPHA)
            generator = torch.Generator(device=device).manual_seed(seed + block * 1009 + site_index)
            train_order = torch.randperm(train.shape[0], generator=generator, device=device)
            heldout_order = torch.randperm(heldout.shape[0], generator=generator, device=device)
            sites.append(
                ProjectionSite(
                    block,
                    site_name,
                    x_base_train,
                    x_base_heldout,
                    train,
                    heldout,
                    weight,
                    folded_weight,
                    scale,
                    train_order,
                    heldout_order,
                )
            )
    provenance = {
        "capture_manifest": str((capture_path / "manifest.json").resolve()),
        "capture_source_sha256": manifest["source"]["sha256"],
        "corpus_token_sha256": manifest["corpus"]["token_stream"]["sha256"],
        "blocks": blocks,
        "sites": [f"{site.block}:{site.name}" for site in sites],
    }
    return sites, provenance


def aggregate_metrics(
    sites: list[ProjectionSite], rotation: torch.Tensor, heldout_limit: int
) -> dict[str, float]:
    totals: dict[str, float] = {}
    with torch.no_grad():
        for site in sites:
            metrics = site.heldout(rotation, heldout_limit)
            for key, value in metrics.items():
                totals[key] = totals.get(key, 0.0) + float(value.item())
    count = float(len(sites))
    return {key: value / count for key, value in totals.items()}


class RuntimeQuantLinear(nn.Module):
    """Linear executed in HipFire's fixed AWQ/FWHT activation basis."""

    def __init__(self, qweight: torch.Tensor, scale: torch.Tensor, route: str):
        super().__init__()
        self.register_buffer("qweight", qweight.float())
        self.register_buffer("scale", scale.float())
        self.route = route
        self.in_features = int(qweight.shape[1])
        self.out_features = int(qweight.shape[0])

    def forward(self, value: torch.Tensor) -> torch.Tensor:
        dtype = value.dtype
        shape = value.shape[:-1]
        flat = value.reshape(-1, self.in_features).float()
        rotated = runtime_basis_rows(flat / self.scale)
        column = rotated.T.contiguous()
        if self.route == "a4":
            quantized = a4_forward(column, FUSED4)[0].T
        elif self.route == "a8":
            quantized = a8_forward(column, "f32")[0].T
        else:
            raise ValueError(self.route)
        output = quantized @ self.qweight.T
        return output.reshape(*shape, self.out_features).to(dtype)


def _replace_module(root: nn.Module, dotted: str, replacement: nn.Module) -> None:
    parent = root
    pieces = dotted.split(".")
    for piece in pieces[:-1]:
        parent = getattr(parent, piece)
    setattr(parent, pieces[-1], replacement)


def _block_scales(
    capture_path: Path, manifest: dict[str, Any], block: int, device: torch.device
) -> dict[str, torch.Tensor]:
    block_meta = manifest["capture"]["blocks"][str(block)]
    result: dict[str, torch.Tensor] = {}
    split_sequence = int(manifest["corpus"]["train_sequences"])
    seq_len = int(manifest["corpus"]["sequence_length"])
    for site, meta in block_meta["producer_sites"].items():
        shape = tuple(int(value) for value in meta["shape"])
        array = np.memmap(capture_path / meta["file"], dtype="<f4", mode="r", shape=shape)
        indices = np.asarray(meta["global_sample_indices"], dtype=np.int64)
        train = torch.from_numpy(
            np.asarray(array[indices < split_sequence * seq_len]).copy()
        ).to(device)
        result[site] = compute_awq_scales(train.square().sum(dim=0), ALPHA)
    return result


def _quantized_folded_layer(
    source: SafeTensorSource,
    config: Any,
    block: int,
    rotation: torch.Tensor,
    scales: dict[str, torch.Tensor],
    route: str,
    device: torch.device,
) -> nn.Module:
    layer = instantiate_layer(source, config, block, device)
    input_site, post_site = _site_names(block)
    specs: list[tuple[str, str, str]] = []
    if block % 4 == 3:
        specs.extend(
            (name, "reader", input_site)
            for name in ("self_attn.q_proj", "self_attn.k_proj", "self_attn.v_proj")
        )
        specs.append(("self_attn.o_proj", "writer", "mixer_out"))
    else:
        specs.extend(
            (name, "reader", input_site)
            for name in (
                "linear_attn.in_proj_qkv",
                "linear_attn.in_proj_z",
                "linear_attn.in_proj_a",
                "linear_attn.in_proj_b",
            )
        )
        specs.append(("linear_attn.out_proj", "writer", "mixer_out"))
    specs.extend(
        (
            ("mlp.gate_proj", "reader", post_site),
            ("mlp.up_proj", "reader", post_site),
            ("mlp.down_proj", "writer", "silu_mul_down"),
        )
    )
    input_gain = bf16_gain(layer.input_layernorm.weight).to(device)
    post_gain = bf16_gain(layer.post_attention_layernorm.weight).to(device)
    with torch.no_grad():
        for dotted, role, site in specs:
            module = layer
            for piece in dotted.split("."):
                module = getattr(module, piece)
            weight = module.weight.float()
            if role == "reader":
                gain = post_gain if dotted.startswith("mlp.") else input_gain
                natural = (weight * gain) @ rotation
            else:
                natural = rotation.T @ weight
            scale = scales[site]
            encoded = runtime_basis_rows(natural * scale)
            qweight = mq4v2_fake(encoded).detach()
            _replace_module(layer, dotted, RuntimeQuantLinear(qweight, scale, route))
        layer.input_layernorm.weight.zero_()
        layer.post_attention_layernorm.weight.zero_()
    layer.eval()
    return layer


def block_reconstruction_metrics(
    source_path: Path,
    capture_path: Path,
    blocks: list[int],
    rotation: torch.Tensor,
    sequences: int,
    tokens: int,
    device: torch.device,
) -> dict[str, Any]:
    """Measure held-out whole-block BF16 reconstruction on both runtime routes."""
    manifest = json.loads((capture_path / "manifest.json").read_text())
    config = load_config(source_path)
    source = SafeTensorSource(source_path)
    train_sequences = int(manifest["corpus"]["train_sequences"])
    selected = slice(train_sequences, train_sequences + sequences)
    route_rows: dict[str, list[dict[str, float]]] = {"a4": [], "a8": []}
    for block in blocks:
        input_meta = manifest["capture"]["boundaries"][str(block)]
        output_meta = manifest["capture"]["boundaries"][str(block + 1)]
        input_shape = tuple(int(value) for value in input_meta["shape"])
        output_shape = tuple(int(value) for value in output_meta["shape"])
        original_input = _read_bf16_memmap(
            capture_path / input_meta["file"], input_shape, selected
        )[:, :tokens].to(device)
        teacher = _read_bf16_memmap(
            capture_path / output_meta["file"], output_shape, selected
        )[:, :tokens].to(device)
        rotated_input = (original_input.float() @ rotation).to(torch.bfloat16)
        rotated_teacher = teacher.float() @ rotation
        position_embeddings, positions, causal = rotary_and_masks(
            config, tokens, device
        )
        scales = _block_scales(capture_path, manifest, block, device)
        for route in ("a4", "a8"):
            layer = _quantized_folded_layer(
                source, config, block, rotation, scales, route, device
            )
            with torch.inference_mode():
                output = layer_forward(
                    layer,
                    rotated_input,
                    position_embeddings,
                    positions,
                    causal,
                    str(config.layer_types[block]),
                ).float()
            error = output - rotated_teacher
            numerator = float(error.square().sum().item())
            denominator = float(rotated_teacher.square().sum().item())
            route_rows[route].append(
                {
                    "block": block,
                    "relative_mse": numerator / max(denominator, 1e-30),
                    "max_abs": float(error.abs().max().item()),
                    "rms": float(error.square().mean().sqrt().item()),
                    "reference_rms": float(
                        rotated_teacher.square().mean().sqrt().item()
                    ),
                }
            )
            del layer, output, error
            torch.cuda.empty_cache()
        del original_input, teacher, rotated_input, rotated_teacher
    return {
        route: {
            "mean_relative_mse": sum(row["relative_mse"] for row in rows)
            / len(rows),
            "blocks": rows,
        }
        for route, rows in route_rows.items()
    }


def fit(args: argparse.Namespace) -> dict[str, Any]:
    device = require_gpu()
    torch.manual_seed(args.seed)
    blocks = [int(value) for value in args.blocks.split(",")]
    sites, provenance = load_projection_sites(
        args.source, args.capture, blocks, args.weight_rows, device, args.seed
    )
    rotation = identity_rotation(device)
    initial_orth = orthogonality_error(rotation)
    initial = aggregate_metrics(sites, rotation, args.heldout_samples)
    initial_block = None
    if not args.skip_block_eval:
        initial_block = block_reconstruction_metrics(
            args.source,
            args.capture,
            blocks,
            rotation,
            args.block_eval_sequences,
            args.block_eval_tokens,
            device,
        )
        print(json.dumps({"step": 0, "block_reconstruction": initial_block}, sort_keys=True), flush=True)
    history: list[dict[str, Any]] = [{"step": 0, "heldout": initial}]
    started = time.monotonic()
    actual_steps: list[float] = []
    for step in range(args.steps):
        rotation = rotation.detach().requires_grad_(True)
        metrics_per_site = [
            site.loss(
                rotation,
                args.batch_samples,
                step,
                args.activation_weight,
            )
            for site in sites
        ]
        loss = torch.stack([metrics["loss"] for metrics in metrics_per_site]).mean()
        loss.backward()
        schedule = 0.5 * (1.0 + math.cos(math.pi * step / max(args.steps, 1)))
        requested_lr = args.lr * schedule
        with torch.no_grad():
            rotation, actual_lr = cayley_sgd_step(rotation, rotation.grad, requested_lr)
        actual_steps.append(actual_lr)
        number = step + 1
        if number % args.eval_every == 0 or number == args.steps:
            heldout = aggregate_metrics(sites, rotation, args.heldout_samples)
            row = {
                "step": number,
                "train_loss": float(loss.item()),
                "requested_lr": requested_lr,
                "actual_cayley_step": actual_lr,
                "heldout": heldout,
            }
            history.append(row)
            print(json.dumps(row, sort_keys=True), flush=True)
    final = history[-1]["heldout"]
    projection_a4_improvement = (initial["output4"] - final["output4"]) / max(
        initial["output4"], 1e-30
    )
    activation_improvement = (initial["activation4"] - final["activation4"]) / max(
        initial["activation4"], 1e-30
    )
    final_block = None
    if not args.skip_block_eval:
        final_block = block_reconstruction_metrics(
            args.source,
            args.capture,
            blocks,
            rotation,
            args.block_eval_sequences,
            args.block_eval_tokens,
            device,
        )
        print(
            json.dumps(
                {"step": args.steps, "block_reconstruction": final_block},
                sort_keys=True,
            ),
            flush=True,
        )
        initial_a4 = initial_block["a4"]["mean_relative_mse"]
        final_a4 = final_block["a4"]["mean_relative_mse"]
        a4_improvement = (initial_a4 - final_a4) / max(initial_a4, 1e-30)
        a8_feasible = (
            final_block["a8"]["mean_relative_mse"]
            <= 1.01 * initial_block["a8"]["mean_relative_mse"]
        )
    else:
        a4_improvement = projection_a4_improvement
        a8_feasible = final["output8"] <= 1.01 * initial["output8"]
