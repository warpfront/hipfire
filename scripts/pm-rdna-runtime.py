"""Project the pinned lossless XML catalogs into variant-keyed runtime rows.

Census tables remain the independent byte/field-exception regression set. This
projection keeps every XML encoding, including named unavailable graphics rows.
Bit layouts and conditions are consumed directly from the catalogs by the codec.
"""
import json
from pathlib import Path

ISA = Path(__file__).resolve().parents[1] / 'crates/peacemaker-ir/isa'


def form(encoding):
    name = encoding.removeprefix('ENC_')
    for prefix, value in [('SOP1', 'sop1'), ('SOP2', 'sop2'), ('SOPC', 'sopc'),
                          ('SOPK', 'sopk'), ('SOPP', 'sopp'), ('SMEM', 'smem'),
                          ('VOP3P', 'vop3p'), ('VOP3', 'vop3'), ('VOPD', 'vopd'),
                          ('VOP1', 'vop1'), ('VOP2', 'vop2'), ('VOPC', 'vopc')]:
        if name.startswith(prefix):
            return value
    return {'DS': 'ds', 'VDS': 'ds', 'LDSDIR': 'ds', 'VDSDIR': 'ds',
            'FLAT_GLOBAL': 'global', 'VGLOBAL': 'global',
            'FLAT_SCRATCH': 'scratch', 'VSCRATCH': 'scratch',
            'FLAT': 'flat', 'VFLAT': 'flat', 'MUBUF': 'buffer',
            'MTBUF': 'buffer', 'VBUFFER': 'buffer', 'MIMG': 'image',
            'MIMG_NSA1': 'image', 'VIMAGE': 'image', 'VSAMPLE': 'image',
            'VINTERP': 'vinterp', 'EXP': 'export', 'VEXPORT': 'export'}[name]


def counters(header, row, kind):
    """Counter families follow the existing RDNA ISA-table counter convention."""
    if not row['memory'] and kind != 'ds':
        return '-'
    gfx12 = header['target'] == 'gfx12'
    if kind == 'ds':
        return 'Ds:1' if gfx12 else 'Lgkm:1'
    if kind == 'smem':
        return 'Km:1' if gfx12 else 'Lgkm:1'
    read = any(op['Input'] == 'true' for op in row['memory'])
    write = any(op['Output'] == 'true' for op in row['memory'])
    load, store = ('Load', 'Store') if gfx12 else ('Vm', 'Vs')
    if read and write:
        result = f'{load}:1@rtn,{store}:1@nortn'
    else:
        result = f'{load if read else store}:1'
    if kind == 'flat':
        result += ',Ds:1' if gfx12 else ',Lgkm:1'
    return result

def project(header, row):
    layout = header['encodings'][row['encoding']]
    operands = [o for o in row['operands'] if o['IsImplicit'] == 'false'
                and o.get('FieldName') in layout['fields']]
    kind = form(row['encoding'])
    atomic = kind in ('global', 'buffer', 'flat', 'scratch') and any(
        op['Input'] == 'true' for op in row['memory']) and any(
        op['Output'] == 'true' for op in row['memory'])
    grammar = ','.join(f"{o['FieldName']}{'@rtn' if atomic and o['Output'] == 'true' else ''}:{o['OperandSize']}"
                       for o in operands) or '-'
    defs = ','.join(o['FieldName'] for o in operands if o['Output'] == 'true') or '-'
    uses = ','.join(o['FieldName'] for o in operands if o['Input'] == 'true') or '-'
    implicit = []
    for op in row['operands']:
        special = {'OPR_SSRC_SPECIAL_SCC': 'scc', 'OPR_VCC': 'vcc',
                   'OPR_EXEC': 'exec', 'OPR_SDST_EXEC': 'exec',
                   'OPR_SDST_M0': 'm0'}.get(op['OperandType'])
        if special and 'FieldName' not in op:
            implicit.append(special + ':' + ('r' if op['Input'] == 'true' else '')
                            + ('w' if op['Output'] == 'true' else ''))
    rules = []
    for name, ranges in layout['fields'].items():
        width = sum(w for _, w in ranges)
        rules.append(f'{name}:honored:{(1 << width) - 1:x}')
    sample = row['oracle'].get('decoded', [row['name']])
    sample = sample[0] if sample else row['name']
    data = bytes.fromhex(row['oracle'].get('candidate', ''))
    words = ' '.join(f'{int.from_bytes(data[i:i+4], "little"):08x}'
                     for i in range(0, len(data), 4)) or '-'
    return '\t'.join([row['name'], kind, f"{row['opcode']:x}",
                      grammar, defs, uses, ','.join(implicit) or '-', counters(header, row, kind), sample,
                      words, ','.join(rules), row['encoding'], row['condition'],
                      str(row['variant'])])


def main():
    for target in ('gfx1100', 'gfx1151', 'gfx12'):
        header, *rows = [json.loads(line) for line in (ISA / f'{target}.xml.jsonl').read_text().splitlines()]
        text = f"# Generated by scripts/pm-rdna-runtime.py; XML sha256 {header['sha256']}\n"
        text += '\n'.join(project(header, row) for row in rows) + '\n'
        (ISA / f'{target}.runtime.tbl').write_text(text)


if __name__ == '__main__':
    main()
